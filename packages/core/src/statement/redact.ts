/**
 * What a statement is stripped of before it leaves the phone.
 *
 * The page text goes to a model for reading, so the first rule is to send as
 * little as will do. A statement's header block (the holder's name, address,
 * e-mail, phone, customer id, account number) has nothing to do with the
 * transactions, so it is not sent at all. Whatever identifiers are left inside
 * the table (an account or card number in a narration, a mobile number in a UPI
 * handle, a PAN) are masked to their last four digits.
 *
 * What is deliberately kept: dates, amounts, balances and the payment
 * references (UPI RRN, NEFT UTR, cheque numbers). Those are the data.
 * Counterparty names inside narrations stay too; categorising them is the point.
 * The consent line in the app says so.
 *
 * Pure, and tested on its own. The PDF password never reaches this function or
 * any other in this package.
 */

export interface RedactionStats {
  /** Lines removed as header, footer or page furniture. */
  readonly linesDropped: number;
  /** Identifiers masked to their last four digits (or removed outright). */
  readonly masked: number;
}

export interface RedactedStatement {
  readonly pages: readonly string[];
  readonly stats: RedactionStats;
}

export interface RedactOptions {
  /** Strings to scrub wherever they occur: the holder's own name, for one. Case-insensitive. */
  readonly secrets?: readonly string[];
}

const MONTH = '(?:jan|feb|mar|apr|may|jun|jul|aug|sep|sept|oct|nov|dec)[a-z]*';
/** A date at the start of a line: 01/10/26, 01-10-2026, 1 Oct 2026, 01-Oct-26, 2026-10-01. */
const LEADING_DATE = new RegExp(
  '^\\s*(?:\\d{1,2}[-/. ]\\d{1,2}[-/. ]\\d{2,4}|\\d{1,2}[-/. ]' +
    MONTH +
    '[-/. ,]+\\d{2,4}|\\d{4}-\\d{2}-\\d{2})(?!\\d)',
  'i',
);
const AMOUNT_TOKEN = /(?<![\d.])\d{1,3}(?:,\d{2,3})*\.\d{2}(?!\d)|(?<![\d.])\d+\.\d{2}(?!\d)/;

/** The header row of the transaction table. Three of these words make it one. */
const COLUMN_WORDS = [
  /\bdate\b/i,
  /\b(?:narration|description|particulars|remarks|details)\b/i,
  /\b(?:withdrawal|withdrawals|debit|debits|dr)\b/i,
  /\b(?:deposit|deposits|credit|credits|cr)\b/i,
  /\bbalance\b|\bbal\b/i,
  /\b(?:chq|cheque|ref)\b/i,
];

function isColumnHeader(line: string): boolean {
  return COLUMN_WORDS.filter((word) => word.test(line)).length >= 3;
}

function isTransactionLine(line: string): boolean {
  return LEADING_DATE.test(line) && AMOUNT_TOKEN.test(line);
}

/** Lines that are the bank talking, not a transaction continuing. */
const FURNITURE =
  /\b(?:registered office|computer generated|does not require|statement of account|statement summary|page\s*\d+\s*(?:of|\/)\s*\d+|gstin|cin\s*:|www\.|https?:|customer care|toll free|nomination|closing balance|opening balance|generated on|generated by|end of statement|account branch|branch address|ifsc|micr|issued)\b/i;

function isFurniture(line: string): boolean {
  return FURNITURE.test(line);
}

/** `1234567890123456` -> `XXXXXXXXXXXX3456`, any separators inside kept off. */
function maskToLastFour(digits: string): string {
  const clean = digits.replace(/\D/g, '');
  return `${'X'.repeat(Math.max(0, clean.length - 4))}${clean.slice(-4)}`;
}

const LABELLED_NUMBER = new RegExp(
  '\\b(a\\/c|acct|account|a\\/c\\.?\\s*no|card|customer\\s*id|cust\\.?\\s*id|crn|cif|folio|routing|aba|sort\\s*code|bsb|member\\s*id)' +
    '(\\s*(?:no\\.?|number|num|#)?\\s*[:.\\-]?\\s*)' +
    '((?:[xX*]+[\\s-]*)?\\d[\\d\\s-]{4,22}\\d)',
  'gi',
);
const CARD_SHAPED = /(?<![\d-])(?:\d{4}[ -]){3}\d{4}(?![\d-])|(?<!\d)\d{16}(?!\d)/g;
const MOBILE = /(?<![\d.])(?:\+91[ -]?|91[ -]|0)?([6-9]\d{9})(?!\d)/g;
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/g;
const PAN = /\b[A-Z]{5}\d{4}[A-Z]\b/g;
/** US social security number. */
const SSN = /(?<![\d-])\d{3}-\d{2}-\d{4}(?![\d-])/g;
/** A UK IBAN, which is an account number with a country on it. */
const IBAN = /\b[A-Z]{2}\d{2}\s?[A-Z]{4}(?:\s?\d{4}){3}\s?\d{2}\b/g;
const AADHAAR = /(?<![\d-])\d{4}[ -]\d{4}[ -]\d{4}(?![\d-])/g;

/**
 * Long digit runs that are plainly an account number rather than a reference:
 * 11 to 18 digits standing alone. A UPI RRN / IMPS ref is exactly 12, a UTR has
 * letters, a cheque is 6, so 12 stays and the rest is masked.
 */
const LONG_DIGITS = /(?<![\d.\w])(\d{11}|\d{13,18})(?![\d\w])/g;

function maskLine(line: string, secrets: readonly RegExp[], count: { n: number }): string {
  let out = line;
  const hit = <T extends unknown[]>(fn: (...args: T) => string) => {
    return (...args: T): string => {
      count.n += 1;
      return fn(...args);
    };
  };
  // Labelled numbers first: "A/c No. 50100123456789" is masked whatever its length.
  out = out.replace(
    LABELLED_NUMBER,
    hit((_all: string, label: string, sep: string, number: string) => {
      return `${label}${sep}${maskToLastFour(number)}`;
    }),
  );
  out = out.replace(
    EMAIL,
    hit((address: string) => {
      const [, domain = ''] = address.split('@');
      return `***@${domain}`;
    }),
  );
  // Mobiles after e-mail so "9876543210@ybl" is handled: the handle's digits are masked.
  out = out.replace(
    MOBILE,
    hit((_all: string, number: string) => maskToLastFour(number)),
  );
  out = out.replace(
    PAN,
    hit(() => 'XXXXXXXXXX'),
  );
  out = out.replace(
    SSN,
    hit(() => 'XXX-XX-XXXX'),
  );
  out = out.replace(
    IBAN,
    hit((value: string) => maskToLastFour(value)),
  );
  out = out.replace(
    AADHAAR,
    hit((value: string) => maskToLastFour(value)),
  );
  out = out.replace(
    CARD_SHAPED,
    hit((value: string) => maskToLastFour(value)),
  );
  out = out.replace(
    LONG_DIGITS,
    hit((value: string) => maskToLastFour(value)),
  );
  for (const secret of secrets) {
    out = out.replace(
      secret,
      hit(() => '[name]'),
    );
  }
  return out;
}

/**
 * Mask identifiers in text that has already been trimmed, without cutting any
 * lines. The edge function runs this over what it is sent as a second line of
 * defence: an older or buggy app that forgot to mask still cannot make an
 * account number reach a model.
 */
export function maskIdentifiers(text: string): string {
  const count = { n: 0 };
  return text
    .split(/\r?\n/)
    .map((line) => maskLine(line, [], count))
    .join('\n');
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * One page: cut the page furniture and keep the table.
 *
 * The kept window runs from the table's column header (or, on a page without
 * one, its first transaction line) to the last transaction line plus the few
 * continuation lines a wrapped narration needs. A page with neither is a page
 * with no transactions on it, and contributes nothing.
 */
function trimPage(lines: readonly string[]): { kept: string[]; dropped: number } {
  const header = lines.findIndex(isColumnHeader);
  const firstTxn = lines.findIndex(isTransactionLine);
  if (firstTxn < 0) return { kept: [], dropped: lines.length };
  const start = header >= 0 && header < firstTxn ? header : firstTxn;

  let lastTxn = firstTxn;
  lines.forEach((line, i) => {
    if (i >= firstTxn && isTransactionLine(line)) lastTxn = i;
  });
  let end = lastTxn;
  for (let i = lastTxn + 1; i < Math.min(lines.length, lastTxn + 4); i += 1) {
    const line = lines[i]!;
    if (isFurniture(line) || isColumnHeader(line) || line.trim() === '') break;
    end = i;
  }
  const kept = lines
    .slice(start, end + 1)
    .filter((line) => line.trim() !== '' && (isColumnHeader(line) || !isFurniture(line)));
  return { kept, dropped: lines.length - kept.length };
}

/** Redact the text layer of a statement, page by page. */
export function redactStatementText(
  pages: readonly string[],
  options: RedactOptions = {},
): RedactedStatement {
  const secrets = (options.secrets ?? [])
    .map((s) => s.trim())
    .filter((s) => s.length >= 3)
    .map((s) => new RegExp(escapeRegExp(s).replace(/\s+/g, '\\s+'), 'gi'));
  const count = { n: 0 };
  let linesDropped = 0;

  const out = pages.map((page) => {
    const { kept, dropped } = trimPage(page.split(/\r?\n/));
    linesDropped += dropped;
    return kept.map((line) => maskLine(line, secrets, count)).join('\n');
  });
  return { pages: out, stats: { linesDropped, masked: count.n } };
}

/**
 * A table the person already has in a spreadsheet, as rows of cells, scrubbed
 * the same way: only used when a spreadsheet is sent for AI reading.
 */
export function redactCells(
  rows: readonly (readonly string[])[],
  options: RedactOptions = {},
): readonly (readonly string[])[] {
  const secrets = (options.secrets ?? [])
    .map((s) => s.trim())
    .filter((s) => s.length >= 3)
    .map((s) => new RegExp(escapeRegExp(s).replace(/\s+/g, '\\s+'), 'gi'));
  const count = { n: 0 };
  return rows.map((row) => row.map((cell) => maskLine(cell, secrets, count)));
}
