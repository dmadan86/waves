/**
 * Builds the self-contained HTML page the statement PDF reader loads in a
 * hidden WebView: pdf.js (legacy build, for older Android WebViews), its worker
 * (run on the page's own thread, so no Worker or blob URL is needed) and a small
 * glue script, all inline. Nothing is fetched at run time.
 *
 *   node apps/mobile/scripts/build-pdf-reader.mjs          write the generated module
 *   node apps/mobile/scripts/build-pdf-reader.mjs --check  fail if it is out of date
 *
 * The output, src/lib/statementImport/pdfReaderHtml.generated.ts, is committed
 * because Metro does not run this at bundle time. A unit test runs the same
 * build, so upgrading pdfjs-dist without regenerating fails CI.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
export const OUTPUT = join(here, '../src/lib/statementImport/pdfReaderHtml.generated.ts');

const pdfjsRoot = () => dirname(require.resolve('pdfjs-dist/package.json'));
const pdfjsFile = (name) => join(pdfjsRoot(), 'legacy/build', name);

/** `export{a as b,c}` at the end of a module -> an assignment a classic script can run. */
function exportsToGlobal(source, globalName) {
  const match = /export\s*\{([^}]*)\}\s*;?\s*$/.exec(source);
  if (!match) throw new Error(`no trailing export list found for ${globalName}`);
  const fields = match[1]
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => {
      const [local, exported] = part.split(/\s+as\s+/);
      return `${JSON.stringify(exported ?? local)}:${local}`;
    });
  // An IIFE keeps the module's top-level names out of the page's shared script scope
  // (two modules in one page would otherwise redeclare each other's classes), and
  // "use strict" keeps the semantics a module has.
  const body = source.slice(0, match.index) + `globalThis.${globalName}={${fields.join(',')}};`;
  return `(function(){"use strict";${body}\n})();`;
}

/** A classic script has no `import.meta`; pdf.js only reads it on its Node path. */
const noImportMeta = (source) => source.replaceAll('import.meta.url', '"file:///pdf.js"');

/** Keeps a `</script` inside the library from ending the tag early. */
const inline = (source) => source.replaceAll('</script', '<\\/script').replaceAll('<!--', '<\\!--');

export function buildHtml() {
  const lib = exportsToGlobal(
    noImportMeta(readFileSync(pdfjsFile('pdf.min.mjs'), 'utf8')),
    'pdfjsLib',
  );
  const worker = exportsToGlobal(
    noImportMeta(readFileSync(pdfjsFile('pdf.worker.min.mjs'), 'utf8')),
    'pdfjsWorker',
  );
  const glue = readFileSync(join(here, 'pdf-reader-glue.js'), 'utf8');
  return [
    '<!doctype html><html><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1"></head><body>',
    `<script>${inline(lib)}</script>`,
    `<script>${inline(worker)}</script>`,
    `<script>${inline(glue)}</script>`,
    '</body></html>',
  ].join('\n');
}

export function buildModule() {
  const { version } = JSON.parse(readFileSync(join(pdfjsRoot(), 'package.json'), 'utf8'));
  return (
    '// @generated by apps/mobile/scripts/build-pdf-reader.mjs; do not edit.\n' +
    `// pdfjs-dist ${version} (legacy build) + scripts/pdf-reader-glue.js, inlined.\n` +
    `export const PDF_READER_HTML: string = ${JSON.stringify(buildHtml())};\n`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildModule();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
    if (current !== next) {
      console.error(
        'pdfReaderHtml.generated.ts is out of date. Run: node apps/mobile/scripts/build-pdf-reader.mjs',
      );
      process.exit(1);
    }
    console.log('pdfReaderHtml.generated.ts is up to date.');
  } else {
    writeFileSync(OUTPUT, next);
    console.log(`wrote ${OUTPUT} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
